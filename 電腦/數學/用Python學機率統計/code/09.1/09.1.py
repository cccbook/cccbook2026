parent = []
child = []
for p, c, k in CELLS:
    parent += [p] * k
    child += [c] * k

print("樣本數 n =", len(parent))
print("父代平均身高 x: 平均 %.4f, 最小 %.1f, 最大 %.1f" % (r.mean(parent), min(parent), max(parent)))
print("子代身高     y: 平均 %.4f, 最小 %.1f, 最大 %.1f" % (r.mean(child), min(child), max(child)))

# ---- 手算最小平方法 --------------------------------------------------
xb = r.mean(parent)
yb = r.mean(child)
sxy = 0.0
sxx = 0.0
for xi, yi in zip(parent, child):
    sxy += (xi - xb) * (yi - yb)
    sxx += (xi - xb) ** 2
b_hand = sxy / sxx
a_hand = yb - b_hand * xb
print()
print("Sxy = %.6f, Sxx = %.6f" % (sxy, sxx))
print("斜率 b = Sxy/Sxx = %.6f" % b_hand)
print("截距 a = ybar - b*xbar = %.6f" % a_hand)

# ---- 與 r.lm 對照 ----------------------------------------------------
m = r.lm(child, [parent], names=["parent"])
print()
print("r.lm 的係數：")
print("  (Intercept) = %.6f" % m.coefficients[0])
print("  parent      = %.6f" % m.coefficients[1])
print("手算與 r.lm 的最大差異 = %.3e" % max(abs(a_hand - m.coefficients[0]), abs(b_hand - m.coefficients[1])))

# ---- 散布圖 + 擬合線 -------------------------------------------------
